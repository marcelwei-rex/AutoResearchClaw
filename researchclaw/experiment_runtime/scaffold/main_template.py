def _as_decimal(value):
    if isinstance(value, bool):
        raise ValueError("boolean is not a metric value")
    if isinstance(value, Decimal):
        number = value
    elif isinstance(value, int):
        number = Decimal(value)
    else:
        raise TypeError("metric authority must originate as Decimal or integer")
    if not number.is_finite():
        raise ValueError("metric value must be finite")
    return number


def _decimal_mean(values):
    numbers = [_as_decimal(value) for value in values]
    if not numbers:
        raise ValueError("cannot aggregate an empty metric sequence")
    with localcontext() as context:
        context.prec = DECIMAL_PRECISION
        context.rounding = ROUND_HALF_EVEN
        return sum(numbers, Decimal(0)) / Decimal(len(numbers))


def _decimal_ratio(numerator, denominator):
    if denominator <= 0:
        raise ValueError("metric denominator must be positive")
    with localcontext() as context:
        context.prec = DECIMAL_PRECISION
        context.rounding = ROUND_HALF_EVEN
        return Decimal(numerator) / Decimal(denominator)


def _json_number_text(value):
    number = _as_decimal(value)
    if number == 0:
        return "0"
    text = format(number, "f")
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text


def _json_text(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, Decimal):
        return _json_number_text(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple)):
        return "[" + ",".join(_json_text(item) for item in value) + "]"
    if isinstance(value, dict):
        if not all(isinstance(key, str) for key in value):
            raise TypeError("JSON object keys must be strings")
        return "{{" + ",".join(
            json.dumps(key, ensure_ascii=False) + ":" + _json_text(value[key])
            for key in sorted(value)
        ) + "}}"
    raise TypeError(f"unsupported JSON value: {{type(value).__name__}}")


def _make_synthetic_hpc(seed: int, n_train: int = 240, n_test: int = 160):
    rng = np.random.default_rng(seed)
    n_features = 8
    x_train_benign = rng.normal(0.0, 1.0, size=(n_train // 2, n_features))
    x_train_attack = rng.normal(0.0, 1.0, size=(n_train // 2, n_features))
    x_train_attack[:, 2:5] += rng.normal(2.0, 0.25, size=(n_train // 2, 3))
    x_train_attack[:, 6] += rng.normal(1.4, 0.2, size=(n_train // 2,))
    x_train = np.vstack([x_train_benign, x_train_attack])
    y_train = np.array([0] * (n_train // 2) + [1] * (n_train // 2), dtype=int)

    x_test_benign = rng.normal(0.0, 1.0, size=(n_test // 2, n_features))
    x_test_attack = rng.normal(0.0, 1.0, size=(n_test // 2, n_features))
    x_test_attack[:, 2:5] += rng.normal(1.7, 0.35, size=(n_test // 2, 3))
    x_test_attack[:, 6] += rng.normal(1.1, 0.25, size=(n_test // 2,))
    x_test = np.vstack([x_test_benign, x_test_attack])
    y_test = np.array([0] * (n_test // 2) + [1] * (n_test // 2), dtype=int)

    perm_train = rng.permutation(len(y_train))
    perm_test = rng.permutation(len(y_test))
    return x_train[perm_train], y_train[perm_train], x_test[perm_test], y_test[perm_test]


def _as_binary_predictions(values, expected_len: int):
    arr = np.asarray(values)
    if arr.shape[0] != expected_len:
        raise ValueError(f"predict returned {{arr.shape[0]}} rows; expected {{expected_len}}")
    if arr.ndim > 1:
        arr = arr.reshape((expected_len, -1))[:, 0]
    numeric = arr.astype(float)
    if not np.all(np.isfinite(numeric)):
        raise ValueError("predict returned non-finite values")
    arr = np.where(numeric >= 0.5, 1, 0).astype(int)
    return arr


def _score(y_true, y_pred):
    y_true = np.asarray(y_true).astype(int)
    y_pred = np.asarray(y_pred).astype(int)
    tp = int(np.sum((y_true == 1) & (y_pred == 1)))
    tn = int(np.sum((y_true == 0) & (y_pred == 0)))
    fp = int(np.sum((y_true == 0) & (y_pred == 1)))
    fn = int(np.sum((y_true == 1) & (y_pred == 0)))
    precision = _decimal_ratio(tp, max(tp + fp, 1))
    recall = _decimal_ratio(tp, max(tp + fn, 1))
    f1 = _decimal_ratio(2 * tp, max(2 * tp + fp + fn, 1))
    tpr = recall
    tnr = _decimal_ratio(tn, max(tn + fp, 1))
    fpr = _decimal_ratio(fp, max(fp + tn, 1))
    accuracy = _decimal_ratio(tp + tn, max(len(y_true), 1))
    return {{
        "accuracy": accuracy,
        "detection_f1": f1,
        "precision": precision,
        "tpr": tpr,
        "tnr": tnr,
        "fpr": fpr,
    }}


